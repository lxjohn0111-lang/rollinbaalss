// Clicks through every UI screen, capturing screenshots and checking that buttons work.
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const out = process.argv[2] || 'tests/output';
const q = process.argv[3] || 'low';
const fs = await import('fs'); fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
const shot = async (n) => { await page.screenshot({ path: `${out}/${n}.png`, timeout: 120000 }); console.log('shot', n); };
const click = async (sel, text) => { const loc = text ? page.locator(sel, { hasText: text }).first() : page.locator(sel).first(); await loc.click({ timeout: 30000 }); await page.waitForTimeout(400); };
await page.goto(`${process.env.URL || 'http://localhost:5173/'}?q=${q}`);
await page.waitForFunction(() => window.__ready, null, { timeout: 120000 });
await page.waitForTimeout(1500);
await shot('01-menu');
await click('.ui-btn', 'LEVELS'); await shot('02-levels');
await click('.back'); await click('.ui-btn', 'ENDLESS'); await shot('03-endless');
await click('.back'); await click('.ui-btn', 'BALLS'); await page.waitForTimeout(2500); await shot('04-balls');
await click('.ball-card', 'Mirror Chrome'); await shot('04b-ball-select');
await click('.back'); await click('.ui-btn', 'STATS'); await shot('05-stats');
await click('.back'); await click('.ui-btn.gear'); await shot('06-settings');
await click('.back');
// start level 1
await click('.ui-btn', 'PLAY');
await page.waitForFunction(() => window.__game.state === 'playing' && window.__game.mode === 'level', null, { timeout: 120000 });
await page.waitForTimeout(3000);
await shot('07-hud');
await page.keyboard.press('Escape'); await page.waitForTimeout(500); await shot('08-pause');
await click('.ui-btn', 'RESUME');
const st = await page.evaluate(() => ({ paused: window.__game.paused, state: window.__game.state }));
console.log('after resume', JSON.stringify(st));
// fast-forward with the autopilot to the results screen
await page.evaluate(() => { const g = window.__game; g.headless = true; g.simulate(400); g.headless = false; });
await page.waitForTimeout(3500);
await shot('09-results');
const res = await page.evaluate(() => ({ state: window.__game.state, result: window.__game.lastResult, save: window.__game.save.data.levels[0], unlocked: window.__game.save.data.unlocked, coins: window.__game.save.data.coins, ach: Object.keys(window.__game.save.data.achievements) }));
console.log('results', JSON.stringify(res));
await click('.ui-btn', 'NEXT');
await page.waitForFunction(() => window.__game.state === 'playing' && window.__game.levelIndex === 1, null, { timeout: 120000 });
console.log('next level ok');
await page.keyboard.press('Escape'); await page.waitForTimeout(400);
await click('.ui-btn', 'EXIT TO MENU'); await page.waitForTimeout(1500);
console.log('menu after exit', await page.evaluate(() => window.__game.mode));
await click('.ui-btn', 'ENDLESS'); await click('.ui-btn', 'START RUN');
await page.waitForFunction(() => window.__game.state === 'playing' && window.__game.mode === 'endless', null, { timeout: 120000 });
await page.waitForTimeout(2500);
await shot('10-endless-hud');
await page.evaluate(() => { const g = window.__game; g.killBall('fall'); });
await page.waitForTimeout(2500);
await shot('11-gameover');
console.log('over', JSON.stringify(await page.evaluate(() => ({ state: window.__game.state, endless: window.__game.save.data.endless }))));
console.log('ERRORS', JSON.stringify([...new Set(errors)]));
await browser.close();
