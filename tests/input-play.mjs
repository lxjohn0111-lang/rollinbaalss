// Real keyboard playtest of the opening: node tests/input-play.mjs <outdir>
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const out = process.argv[2];
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 960, height: 540 } });
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
await page.goto((process.env.URL || 'http://localhost:5173/') + '?q=low&level=1');
await page.waitForFunction(() => window.__game && window.__game.state === 'intro', null, { timeout: 120000 });
await page.waitForTimeout(500);
await page.screenshot({ path: out + '/p1-ready.png' });
await page.waitForFunction(() => window.__game.state === 'playing', null, { timeout: 60000 });
const st = () => page.evaluate(() => { const g = window.__game, b = g.ball; return { t: +g.run.time.toFixed(2), s: +b.s.toFixed(1), v: +b.speed.toFixed(2), vy: +b.vel.y.toFixed(2), boost: +b.boostMeter.toFixed(1), boosting: b.boosting, grounded: b.grounded, score: g.run.points, combo: g.run.combo, hint: document.querySelector('.hud-hint').textContent }; });
console.log('at GO', JSON.stringify(await st()));
await page.waitForTimeout(800);
console.log('idle 0.8s (no throttle)', JSON.stringify(await st()));
await page.screenshot({ path: out + '/p2-hint.png' });
await page.keyboard.down('KeyW');
await page.waitForTimeout(6000);
console.log('after holding W', JSON.stringify(await st()));
await page.keyboard.down('KeyS');
await page.waitForTimeout(700);
console.log('after S brake', JSON.stringify(await st()));
await page.keyboard.up('KeyS');
await page.waitForTimeout(1200);
await page.keyboard.down('Space');
await page.waitForTimeout(700);
await page.keyboard.up('Space');
console.log('right after jump', JSON.stringify(await st()));
await page.waitForTimeout(800);
await page.evaluate(() => { window.__game.ball.boostMeter = 100; });
await page.keyboard.down('ShiftLeft');
await page.waitForTimeout(900);
console.log('boosting', JSON.stringify(await st()));
await page.screenshot({ path: out + '/p3-boost.png' });
await page.keyboard.up('ShiftLeft');
await page.keyboard.down('KeyA'); await page.waitForTimeout(2500);
const l1 = await page.evaluate(() => window.__game.ball.lat); await page.keyboard.up('KeyA');
await page.keyboard.down('KeyD'); await page.waitForTimeout(2500);
const l2 = await page.evaluate(() => window.__game.ball.lat); await page.keyboard.up('KeyD');
console.log('steer A lat', l1.toFixed(2), 'then D lat', l2.toFixed(2));
await page.waitForTimeout(4000);
console.log('later', JSON.stringify(await st()));
await page.screenshot({ path: out + '/p4-later.png' });
await page.keyboard.up('KeyW');
console.log('errors', JSON.stringify(errs));
await browser.close();
